#!/usr/bin/env python3
"""Minimal AST-based mutation tester. Standard library only.

For a given Python file, generates one mutant per mutable node (comparison
operators, boolean constants, and/or), writes it in place, runs the given
test command, and records whether the test suite caught it (mutant killed,
exit != 0) or not (mutant survived, exit == 0). Restores the original file
after each mutant and at the end.

    python3 mutate_and_test.py <target.py> -- <test command...>

Mutation score = killed / total. A low score on an agent's own test suite,
run against the agent's own implementation, is direct evidence that suite
is weak - it doesn't notice when the logic it's supposed to guard changes.

Each mutant is generated by re-parsing the original source fresh and
re-collecting targets in the same deterministic AST walk order, then
applying the mutation at position `idx` - avoids ever mutating a shared
tree in place.
"""

from __future__ import annotations

import ast
import shutil
import subprocess
import sys
from pathlib import Path

CMP_FLIPS = {
    ast.Eq: ast.NotEq,
    ast.NotEq: ast.Eq,
    ast.Lt: ast.GtE,
    ast.GtE: ast.Lt,
    ast.Gt: ast.LtE,
    ast.LtE: ast.Gt,
}
BOOLOP_FLIPS = {ast.And: ast.Or, ast.Or: ast.And}


class MutationVisitor(ast.NodeVisitor):
    """Collects (node, kind) for every mutable site, in deterministic walk order."""

    def __init__(self) -> None:
        self.targets: list[tuple[ast.AST, str]] = []

    def visit_Compare(self, node: ast.Compare) -> None:
        for i, op in enumerate(node.ops):
            if type(op) in CMP_FLIPS:
                self.targets.append((node, f"cmp[{i}]"))
        self.generic_visit(node)

    def visit_BoolOp(self, node: ast.BoolOp) -> None:
        if type(node.op) in BOOLOP_FLIPS:
            self.targets.append((node, "boolop"))
        self.generic_visit(node)

    def visit_Constant(self, node: ast.Constant) -> None:
        if isinstance(node.value, bool):
            self.targets.append((node, "bool_const"))
        self.generic_visit(node)


def _collect(source: str, filename: str) -> tuple[ast.Module, list[tuple[ast.AST, str]]]:
    tree = ast.parse(source, filename=filename)
    visitor = MutationVisitor()
    visitor.visit(tree)
    return tree, visitor.targets


def _apply(node: ast.AST, kind: str) -> None:
    if kind.startswith("cmp["):
        i = int(kind[4:-1])
        node.ops[i] = CMP_FLIPS[type(node.ops[i])]()  # type: ignore[attr-defined]
    elif kind == "boolop":
        node.op = BOOLOP_FLIPS[type(node.op)]()  # type: ignore[attr-defined]
    elif kind == "bool_const":
        node.value = not node.value  # type: ignore[attr-defined]


def main() -> int:
    if "--" not in sys.argv:
        print("usage: mutate_and_test.py <target.py> -- <test command...>", file=sys.stderr)
        return 2
    sep = sys.argv.index("--")
    target = Path(sys.argv[1])
    test_cmd = " ".join(sys.argv[sep + 1 :])

    original_source = target.read_text(encoding="utf-8")
    _, targets = _collect(original_source, str(target))

    if not targets:
        print(f"NO_MUTANTS: {target} has no mutable comparison/boolean nodes")
        return 0

    total = len(targets)
    killed = 0
    backup = target.with_suffix(target.suffix + ".orig")
    shutil.copy(target, backup)

    try:
        for idx, (_, kind) in enumerate(targets):
            mutant_tree, mutant_targets = _collect(original_source, str(target))
            node, _ = mutant_targets[idx]
            _apply(node, kind)

            target.write_text(ast.unparse(ast.fix_missing_locations(mutant_tree)), encoding="utf-8")
            result = subprocess.run(test_cmd, shell=True, capture_output=True, timeout=120)
            shutil.copy(backup, target)

            status = "killed" if result.returncode != 0 else "SURVIVED"
            if result.returncode != 0:
                killed += 1
            print(f"  mutant {idx + 1}/{total} ({kind}): {status}")
    finally:
        shutil.copy(backup, target)
        backup.unlink()

    score = killed / total if total else 0.0
    print(f"MUTATION_SCORE: {killed}/{total} = {score:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
